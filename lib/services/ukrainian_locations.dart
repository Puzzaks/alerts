/// Immutable metadata for a verified Ukrainian administrative location
/// recognized by `alerts.in.ua` and the PAIOS Alerts extension.
class UkrainianLocation {
  /// Exact Ukrainian name used by `alerts.in.ua` / `alerts_worker` / map data.
  final String canonicalName;

  /// Human-readable English display name.
  final String englishName;

  /// Administrative tier: `'special_city'`, `'oblast'`, `'raion'`, `'city'`, or `'hromada'`.
  final String type;

  /// Parent oblast `canonicalName`, or `null` for top-level oblasts and special cities.
  final String? parentOblast;

  /// Searchable Ukrainian/English aliases and transliterations.
  final List<String> aliases;

  const UkrainianLocation({
    required this.canonicalName,
    required this.englishName,
    required this.type,
    this.parentOblast,
    this.aliases = const <String>[],
  });

  bool get isTopLevel => parentOblast == null;
  bool get isSpecialCity => type == 'special_city';
  bool get isOblast => type == 'oblast';
  bool get isRaion => type == 'raion';
  bool get isCity => type == 'city';
  bool get isHromada => type == 'hromada';

  /// Canonical oblast name associated with this location (or [canonicalName]
  /// for top-level oblasts and special status cities).
  String get oblastCanonicalName => parentOblast ?? canonicalName;

  /// Canonical title without an oblast disambiguation suffix (e.g. `'м. Городок'`).
  String get baseCanonicalName {
    final idx = canonicalName.indexOf(' (');
    return idx > 0 ? canonicalName.substring(0, idx) : canonicalName;
  }

  /// Secondary label for UI lists and disambiguation.
  String get displaySubtitle {
    if (parentOblast != null) return parentOblast!;
    if (isSpecialCity) return 'Special status city';
    return 'Ukraine';
  }

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is UkrainianLocation &&
          runtimeType == other.runtimeType &&
          canonicalName == other.canonicalName;

  @override
  int get hashCode => canonicalName.hashCode;

  @override
  String toString() => 'UkrainianLocation($canonicalName / $englishName [$type])';
}

