  /// All fixed selectable Ukrainian administrative locations in ranked order
  /// ([topLevelRegions] first, followed by [raions] and [cities]).
  static const List<UkrainianLocation> allLocations = <UkrainianLocation>[
    ...topLevelRegions,
    ...raions,
    ...cities,
  ];

  static Map<String, UkrainianLocation>? _exactLookup;

  /// Normalizes Ukrainian/English location text for safe comparison.
  ///
  /// Unifies apostrophe variants (`’`, `ʼ`, `` ` `` -> `'`), collapses
  /// whitespace/underscores, lowercases, and trims.
  static String normalizeKey(String input) {
    return input
        .toLowerCase()
        .replaceAll('’', "'")
        .replaceAll('ʼ', "'")
        .replaceAll('`', "'")
        .replaceAll(RegExp(r'[\s_]+'), ' ')
        .trim();
  }

  static Map<String, UkrainianLocation> _getExactLookup() {
    final existing = _exactLookup;
    if (existing != null) return existing;

    final map = <String, UkrainianLocation>{};
    // Index topLevelRegions first, then raions, then cities so top-level
    // entries always own top-level names/aliases, and exact canonical/English
    // names are never shadowed by another entry's alias.
    for (final loc in allLocations) {
      map[normalizeKey(loc.canonicalName)] = loc;
      map[normalizeKey(loc.englishName)] = loc;
    }
    for (final loc in allLocations) {
      for (final alias in loc.aliases) {
        final key = normalizeKey(alias);
        if (key.isEmpty) continue;
        if (loc.canonicalName != loc.baseCanonicalName &&
            (key == normalizeKey(loc.baseCanonicalName) ||
                key == normalizeKey(loc.baseCanonicalName.replaceFirst('м. ', '')))) {
          continue;
        }
        map.putIfAbsent(key, () => loc);
      }
    }

    _exactLookup = map;
    return map;
  }

  /// Resolves [input] to a verified [UkrainianLocation] by exact match against
  /// `canonicalName`, `englishName`, or an unambiguous alias.
  ///
  /// Returns `null` for arbitrary/unrecognized text (such as `"moon"`).
  /// Strictly separates `'м. Київ'` / `'Kyiv City'` from `'Київська область'` /
  /// `'Kyiv Oblast'`, and `'м. Севастополь'` from `'Автономна Республіка Крим'`.
  static UkrainianLocation? findByCanonicalOrAlias(String input) {
    final norm = normalizeKey(input);
    if (norm.isEmpty) return null;
    return _getExactLookup()[norm];
  }

  /// Returns `true` when [input] resolves to a verified location in this catalog.
  static bool isValidLocation(String input) =>
      findByCanonicalOrAlias(input) != null;

  /// Searches the fixed catalog case-insensitively across `canonicalName`,
  /// `englishName`, `parentOblast`, and `aliases`.
  ///
  /// When [query] is empty, returns [allLocations] (with the 27
  /// [topLevelRegions] first). Returns an empty list when nothing matches
  /// (e.g. `"moon"`).
  static List<UkrainianLocation> search(String query, {int? limit}) {
    final norm = normalizeKey(query);
    if (norm.isEmpty) {
      if (limit != null && limit >= 0 && limit < allLocations.length) {
        return allLocations.sublist(0, limit);
      }
      return allLocations;
    }

    final scored = <(int score, int index, UkrainianLocation loc)>[];
    for (var i = 0; i < allLocations.length; i++) {
      final loc = allLocations[i];
      final score = _scoreMatch(loc, norm);
      if (score > 0) {
        scored.add((score, i, loc));
      }
    }

    scored.sort((a, b) {
      final byScore = b.$1.compareTo(a.$1);
      if (byScore != 0) return byScore;
      return a.$2.compareTo(b.$2);
    });

    final results = scored.map((entry) => entry.$3);
    if (limit != null && limit >= 0) {
      return results.take(limit).toList(growable: false);
    }
    return results.toList(growable: false);
  }

  static int _scoreMatch(UkrainianLocation loc, String normQuery) {
    final canon = normalizeKey(loc.canonicalName);
    final baseCanon = normalizeKey(loc.baseCanonicalName);
    final strippedCity = baseCanon.startsWith('м. ')
        ? baseCanon.substring(3)
        : baseCanon;
    final en = normalizeKey(loc.englishName);
    final parent = loc.parentOblast != null
        ? normalizeKey(loc.parentOblast!)
        : '';

    var best = 0;
    void consider(String candidate, int exactScore, int prefixScore, int containsScore) {
      if (candidate.isEmpty) return;
      if (candidate == normQuery) {
        if (exactScore > best) best = exactScore;
      } else if (candidate.startsWith(normQuery)) {
        if (prefixScore > best) best = prefixScore;
      } else if (candidate.contains(normQuery)) {
        if (containsScore > best) best = containsScore;
      }
    }

    consider(canon, 120, 95, 55);
    consider(baseCanon, 115, 92, 52);
    consider(strippedCity, 112, 90, 50);
    consider(en, 118, 94, 54);

    for (final alias in loc.aliases) {
      consider(normalizeKey(alias), 108, 86, 46);
    }

    if (best == 0 && parent.isNotEmpty && parent.contains(normQuery)) {
      best = 18;
    }

    if (best == 0) return 0;

    if (loc.isTopLevel) {
      best += 12;
    } else if (loc.isRaion) {
      best += 4;
    }
    return best;
  }
